(function validateQuestionBank() {
    const errors = [];

    if (!Array.isArray(window.questions)) {
        console.error("SMART SIX: Question bank is not an array.");
        return;
    }

    if (window.questions.length !== 250) {
        errors.push(
            `Expected 250 questions, found ${window.questions.length}.`
        );
    }

    window.questions.forEach((q, index) => {

        const expectedId = index + 1;

        if (q.id !== expectedId) {
            errors.push(
                `Question ${index + 1}: expected id ${expectedId}, found ${q.id}.`
            );
        }

        if (!q.subject) {
            errors.push(`Question ${q.id}: missing subject.`);
        }

        if (!q.difficulty) {
            errors.push(`Question ${q.id}: missing difficulty.`);
        }

        if (!q.question || typeof q.question !== "string") {
            errors.push(`Question ${q.id}: invalid question text.`);
        }

        if (!Array.isArray(q.options) || q.options.length !== 4) {
            errors.push(`Question ${q.id}: must contain exactly 4 options.`);
        }

        if (
            !Number.isInteger(q.answer) ||
            q.answer < 0 ||
            q.answer > 3
        ) {
            errors.push(
                `Question ${q.id}: answer must be an integer from 0 to 3.`
            );
        }

        if (
            Array.isArray(q.options) &&
            q.options.some(
                option => typeof option !== "string" || !option.trim()
            )
        ) {
            errors.push(`Question ${q.id}: contains an empty option.`);
        }
    });

    const ids = window.questions.map(q => q.id);
    const uniqueIds = new Set(ids);

    if (uniqueIds.size !== ids.length) {
        errors.push("Duplicate question IDs detected.");
    }

    if (errors.length) {
        console.error("SMART SIX QUESTION BANK VALIDATION FAILED:");
        errors.forEach(error => console.error("• " + error));
    } else {
        console.log(
            `SMART SIX QUESTION BANK: ${window.questions.length} questions loaded successfully.`
        );
    }
})();
